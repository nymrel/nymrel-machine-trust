import type { RobotsTxtConfig, BotRule, BotPosture } from '../types.js';
import { MachineTrustConfigError } from '../errors.js';

const ROBOTS_CONTROL_CHARACTERS = /[\u0000-\u001f\u007f-\u009f\u2028\u2029]/;
const ROBOTS_PRODUCT_TOKEN = /^(?:\*|[A-Za-z0-9_-]+)$/;

function assertDirectiveValue(field: string, value: unknown): asserts value is string {
  if (typeof value !== 'string' || ROBOTS_CONTROL_CHARACTERS.test(value)) {
    throw new MachineTrustConfigError(
      'INVALID_ROBOTS_DIRECTIVE',
      `${field} must be a string without control characters.`
    );
  }
}

function assertBotName(value: unknown): asserts value is string {
  if (typeof value !== 'string' || !ROBOTS_PRODUCT_TOKEN.test(value)) {
    throw new MachineTrustConfigError(
      'INVALID_ROBOTS_DIRECTIVE',
      'botName must be * or a product token containing only letters, numbers, underscores, and hyphens.'
    );
  }
}

function assertCrawlDelay(value: unknown): asserts value is number {
  if (typeof value !== 'number' || !Number.isFinite(value) || value < 0) {
    throw new MachineTrustConfigError(
      'INVALID_ROBOTS_DIRECTIVE',
      'crawlDelay must be a finite, non-negative number.'
    );
  }
}

